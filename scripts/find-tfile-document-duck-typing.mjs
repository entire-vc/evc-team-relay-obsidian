#!/usr/bin/env node
// One-shot investigation script for (gate4 W9): is `Document`
// ever passed, WITHOUT an explicit cast, into a slot statically typed as
// (or including) Obsidian's own `TFile`? Structural typing means this needs
// no cast to compile -- the `grep -rn "as TFile"` check from W8 only finds
// EXPLICIT casts and provably cannot see this class of site.
//
// Not a permanent tool: a throwaway diagnostic, deleted after this task's
// investigation is written up in the closing comment either way.
//
// W10 UPDATE: kept, not deleted, because the W9 finding got
// fixed and the fix needs a re-check. One correction was required to make the
// re-run meaningful. The fix for the finding was to widen the offending slot
// from `TFile` to an explicit `DiffViewFile = TFile | Document | UnsavedFile`
// union, which forces the compiler to demand a narrowing before any per-kind
// field is read. But that union *includes* `TFile`, so `typeIncludesTFile()`
// matched it and the scanner reported all 16 now-safe sites as findings --
// louder after the fix than before it, which would have trained the next
// reader to ignore it.
//
// The discriminator is whether the DECLARED type already admits `Document`:
//   slot typed `TFile`                          -> hazard (this is the bug)
//   slot typed `TFile | Document | UnsavedFile` -> safe: the compiler knows a
//                                                  Document can arrive and
//                                                  refuses an unguarded read
// So a match is only a finding when the declared type does NOT include
// `Document`. This narrows what the tool reports; it does not weaken it --
// the W9 finding (`file1: TFile` <- `this.document`) still fires under the
// new rule, and is re-confirmed by the positive control described in
// `--self-test` below before any zero-findings run is believed.
import ts from "typescript";
import path from "path";
import fs from "fs";

// --self-test: drop a synthetic positive control into the tree before the
// program is built, so a zero-findings run can be distinguished from a
// detector that has quietly stopped detecting. W9's own methodology note said
// to do this by hand; doing it by hand is exactly the step that gets skipped,
// so it lives in the tool. The fixture is removed in a `finally` below.
const SELF_TEST = process.argv.includes("--self-test");
const CONTROL_FILE = path.resolve("src/__duck_typing_positive_control.ts");
const CONTROL_SOURCE = `// GENERATED by find-tfile-document-duck-typing.mjs --self-test. Deleted on exit.
import type { TFile } from "obsidian";
import type { Document } from "./Document";

declare function takesATFile(file: TFile): void;
declare const someDocument: Document;

export function positiveControl(): void {
	takesATFile(someDocument);
}
`;

if (SELF_TEST) {
	fs.writeFileSync(CONTROL_FILE, CONTROL_SOURCE);
}

function removeControlFile() {
	if (SELF_TEST && fs.existsSync(CONTROL_FILE)) {
		fs.unlinkSync(CONTROL_FILE);
	}
}
process.on("exit", removeControlFile);

const configPath = path.resolve("tsconfig.json");
const configFile = ts.readConfigFile(configPath, ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(configFile.config, ts.sys, path.resolve("."));

// Include test files too -- tsconfig excludes them, but a Document could be
// handed to a TFile-typed slot in a test just as easily as in src.
const rootNames = ts.sys.readDirectory(".", [".ts"], ["node_modules/**", "vaults/**"], ["**/*.ts"])
  .filter((f) => !f.includes("/node_modules/"));

const program = ts.createProgram(rootNames, parsed.options);
const checker = program.getTypeChecker();

let documentType = null;
let tfileType = null;

for (const sf of program.getSourceFiles()) {
  if (sf.isDeclarationFile) continue;
  ts.forEachChild(sf, function visit(node) {
    if (ts.isClassDeclaration(node) && node.name?.text === "Document" && sf.fileName.endsWith("src/Document.ts")) {
      documentType = checker.getTypeAtLocation(node);
    }
    ts.forEachChild(node, visit);
  });
}

// TFile's declaration lives in obsidian's .d.ts -- find it via a symbol import
// resolution instead of re-walking every declaration file.
for (const sf of program.getSourceFiles()) {
  if (!sf.fileName.includes("node_modules/obsidian/obsidian.d.ts")) continue;
  ts.forEachChild(sf, function visit(node) {
    if (ts.isClassDeclaration(node) && node.name?.text === "TFile") {
      tfileType = checker.getTypeAtLocation(node);
    }
    ts.forEachChild(node, visit);
  });
}

if (!documentType || !tfileType) {
  console.error("FATAL: could not resolve Document or TFile type", { documentType: !!documentType, tfileType: !!tfileType });
  process.exit(2);
}

console.log("Document assignable to TFile (structural)?", checker.isTypeAssignableTo(documentType, tfileType));
console.log("TFile assignable to Document?", checker.isTypeAssignableTo(tfileType, documentType));

function typeIncludesDocument(t) {
  const parts = t.isUnion() ? t.types : [t];
  return parts.some((p) => p === documentType || checker.typeToString(p) === "Document");
}
function typeIncludesTFile(t) {
  const parts = t.isUnion() ? t.types : [t];
  return parts.some((p) => p === tfileType || checker.typeToString(p) === "TFile");
}

/**
 * Is this a slot a `Document` can reach WITHOUT the compiler knowing?
 *
 * A declared type that already names `Document` is not the hazard: TS then
 * rejects every unguarded per-kind field read on it, which is the whole point
 * of the W10 fix. Only a slot that admits `TFile` while NOT admitting
 * `Document` lets one through structurally and silently. See the header.
 */
function isUnguardedTFileSlot(declaredType) {
  return typeIncludesTFile(declaredType) && !typeIncludesDocument(declaredType);
}

const findings = [];

for (const sf of program.getSourceFiles()) {
  if (sf.isDeclarationFile) continue;
  if (sf.fileName.includes("/node_modules/")) continue;

  function visit(node) {
    // Call/new expressions: check each argument against the resolved parameter type.
    if (ts.isCallExpression(node) || ts.isNewExpression(node)) {
      const sig = checker.getResolvedSignature(node);
      if (sig && node.arguments) {
        node.arguments.forEach((arg, i) => {
          const param = sig.parameters[i] ?? sig.parameters[sig.parameters.length - 1];
          if (!param) return;
          const paramType = checker.getTypeOfSymbolAtLocation(param, arg);
          if (!isUnguardedTFileSlot(paramType)) return;
          const argType = checker.getTypeAtLocation(arg);
          if (typeIncludesDocument(argType)) {
            const { line } = sf.getLineAndCharacterOfPosition(arg.getStart());
            findings.push({ kind: "call-arg", file: sf.fileName, line: line + 1, text: node.getText().slice(0, 100) });
          }
        });
      }
    }

    // Variable declarations: `const x: TFile = someDocumentExpr`
    if (ts.isVariableDeclaration(node) && node.type && node.initializer) {
      const declaredType = checker.getTypeFromTypeNode(node.type);
      if (isUnguardedTFileSlot(declaredType)) {
        const initType = checker.getTypeAtLocation(node.initializer);
        if (typeIncludesDocument(initType)) {
          const { line } = sf.getLineAndCharacterOfPosition(node.getStart());
          findings.push({ kind: "var-decl", file: sf.fileName, line: line + 1, text: node.getText().slice(0, 100) });
        }
      }
    }

    // Property access on a value narrowly claimed as TFile in a JSDoc/param, but
    // catches assignment expressions too: `x = doc` where x is TFile-typed.
    if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.EqualsToken) {
      const leftType = checker.getTypeAtLocation(node.left);
      if (isUnguardedTFileSlot(leftType)) {
        const rightType = checker.getTypeAtLocation(node.right);
        if (typeIncludesDocument(rightType)) {
          const { line } = sf.getLineAndCharacterOfPosition(node.getStart());
          findings.push({ kind: "assign", file: sf.fileName, line: line + 1, text: node.getText().slice(0, 100) });
        }
      }
    }

    // Return statements: `function f(): TFile { return doc; }`.
    if (ts.isReturnStatement(node) && node.expression) {
      let fn = node;
      while (fn && !ts.isFunctionLike(fn)) fn = fn.parent;
      if (fn) {
        const sig = checker.getSignatureFromDeclaration(fn);
        const returnType = sig && checker.getReturnTypeOfSignature(sig);
        if (returnType && isUnguardedTFileSlot(returnType)) {
          const exprType = checker.getTypeAtLocation(node.expression);
          if (typeIncludesDocument(exprType)) {
            const { line } = sf.getLineAndCharacterOfPosition(node.getStart());
            findings.push({ kind: "return", file: sf.fileName, line: line + 1, text: node.getText().slice(0, 100) });
          }
        }
      }
    }

    // Class property declarations with an initializer: `file: TFile = doc;`.
    if (ts.isPropertyDeclaration(node) && node.type && node.initializer) {
      const declaredType = checker.getTypeFromTypeNode(node.type);
      if (isUnguardedTFileSlot(declaredType)) {
        const initType = checker.getTypeAtLocation(node.initializer);
        if (typeIncludesDocument(initType)) {
          const { line } = sf.getLineAndCharacterOfPosition(node.getStart());
          findings.push({ kind: "prop-decl", file: sf.fileName, line: line + 1, text: node.getText().slice(0, 100) });
        }
      }
    }

    // Array literals with a contextual element type of TFile: `const a: TFile[] = [doc]`.
    if (ts.isArrayLiteralExpression(node)) {
      const arrType = checker.getContextualType(node);
      if (arrType) {
        const elemType = checker.getIndexTypeOfType ? checker.getIndexTypeOfType(arrType, ts.IndexKind.Number) : null;
        if (elemType && isUnguardedTFileSlot(elemType)) {
          node.elements.forEach((el) => {
            const elType = checker.getTypeAtLocation(el);
            if (typeIncludesDocument(elType)) {
              const { line } = sf.getLineAndCharacterOfPosition(el.getStart());
              findings.push({ kind: "array-elem", file: sf.fileName, line: line + 1, text: el.getText().slice(0, 100) });
            }
          });
        }
      }
    }

    // Object literal property assignments: `{ file: doc }` where the
    // contextual type says `file` should be TFile.
    if (ts.isPropertyAssignment(node)) {
      const contextualType = checker.getContextualType(node.initializer);
      if (contextualType && isUnguardedTFileSlot(contextualType)) {
        const initType = checker.getTypeAtLocation(node.initializer);
        if (typeIncludesDocument(initType)) {
          const { line } = sf.getLineAndCharacterOfPosition(node.getStart());
          findings.push({ kind: "obj-prop", file: sf.fileName, line: line + 1, text: node.getText().slice(0, 100) });
        }
      }
    }

    ts.forEachChild(node, visit);
  }
  visit(sf);
}

console.log(`\nFindings: ${findings.length}`);
for (const f of findings) {
  console.log(`  [${f.kind}] ${path.relative(".", f.file)}:${f.line}  ${f.text}`);
}

if (SELF_TEST) {
  // Match on basename: TypeScript normalizes `sf.fileName` (separators, and
  // any symlink in the checkout path), so it need not be string-equal to the
  // absolute path we wrote to.
  const controlName = path.basename(CONTROL_FILE);
  const caught = findings.filter((f) => path.basename(f.file) === controlName);
  removeControlFile();
  if (caught.length === 0) {
    console.error(
      "\nSELF-TEST FAILED: the synthetic positive control (a `Document` passed to a " +
        "`TFile`-typed parameter) was NOT reported. A zero-findings run from this " +
        "build proves nothing.",
    );
    process.exit(2);
  }
  console.log(
    `\nSELF-TEST PASSED: positive control reported (${caught.length} finding(s) in ` +
      `${path.relative(".", CONTROL_FILE)}). Real findings: ${findings.length - caught.length}.`,
  );
}
